"""
The battle's 8x8 labels (Garde, Rang, Coût PM) pre-rendered in the small VWF and baked into the 8x8 font at build
time, in blank kana slots no table maps.

At battle start the game copies a list of 8x8 font codes ($16:FB87) into BG2's tileset, entry k to battle tile
FIRST_TILE + k; the labels are rows of those battle tiles. Vanilla's kana labels, then our single letters
(GRadeginqrsu), sat in LABEL_ENTRIES of that list: the words' baked tiles take them instead, so a label is set as
tight as the field menus' text. `battle_labels.i` gives the list's entries and each label's row.
"""

from __future__ import annotations

from pathlib import Path

from katsuji import VwfFont

from katsuji.script import Table
from utils.bake_names import Glyphs, auto_kern, name_tiles

TILE_BYTES = 16
BLANK = bytes([0xFF, 0x00] * 8)  # the font's empty cell: colour 1 all over
BLANK_CODE = 0xFF
SLOTS = range(0xD2, 0xDD)  # blank, unmapped kana slots of the 8x8 font
FIRST_TILE = 0xDB  # battle tile of the copy list's first entry
LABEL_ENTRIES = range(3, 15)  # the copy list's entries the labels take
LABELS = {  # label: its text, the cells of its row, the blank cells before it (the rest of the row blank)
    "garde": ("Garde", 3, 0),  # the Defend / Row windows' inside width (battle/graphics.s defend_row_length)
    "rang": ("Rang", 3, 0),
    "mp_cost": ("Coût PM", 7, 1),  # centred by whole tiles in the MP cost window
}
TEXTS = {"en": {"garde": "Guard", "rang": "Row", "mp_cost": "MP Cost"}}  # other languages' texts, LABELS' rows


def labels(lang: str = "fr") -> dict[str, tuple[str, int, int]]:
    """LABELS with `lang`'s texts."""
    texts = TEXTS.get(lang, {})
    return {name: (texts.get(name, text), cells, lead) for name, (text, cells, lead) in LABELS.items()}


def bake(font_8x8: bytes, font: VwfFont, glyphs: Glyphs, table: Table, lang: str = "fr") -> tuple[bytes, str]:
    """`font_8x8` with the labels' tiles in SLOTS, and the asm include naming them."""
    texts = labels(lang)
    codes = {name: table.to_bytes(text) for name, (text, _, _) in texts.items()}
    font = auto_kern(font, glyphs, list(codes.values()))
    merged = bytearray(font_8x8)
    slots = iter(SLOTS)
    entries: list[int] = []
    rows: dict[str, list[int]] = {}
    for name, (text, cells, lead) in texts.items():
        tiles = name_tiles(font, codes[name])
        count = len(tiles) // TILE_BYTES
        if lead + count > cells:
            raise ValueError(f"{text!r} takes {lead} + {count} cells, its row has {cells}")
        row = [BLANK_CODE] * lead
        for index in range(count):
            slot = next(slots, None)
            if slot is None:
                raise ValueError(f"the labels outgrow the font's {len(SLOTS)} free slots")
            if len(entries) == len(LABEL_ENTRIES):
                raise ValueError(f"the labels outgrow the copy list's {len(LABEL_ENTRIES)} entries")
            cell = slice(slot * TILE_BYTES, (slot + 1) * TILE_BYTES)
            if merged[cell] != BLANK:
                raise ValueError(f"font tile {slot:#04x} is not blank: a label would overwrite a glyph")
            merged[cell] = tiles[index * TILE_BYTES:(index + 1) * TILE_BYTES]
            row.append(FIRST_TILE + LABEL_ENTRIES[len(entries)])
            entries.append(slot)
        rows[name] = row + [BLANK_CODE] * (cells - len(row))
    entries += [BLANK_CODE] * (len(LABEL_ENTRIES) - len(entries))
    return bytes(merged), _include(entries, rows, texts)


def _db(values: list[int]) -> str:
    return "    .db " + ", ".join(f"0x{value:02X}" for value in values)


def _include(entries: list[int], rows: dict[str, list[int]], texts: dict[str, tuple[str, int, int]]) -> str:
    lines = ['"""Generated by utils/battle_labels.py: the battle labels\' baked tiles."""', "",
             ".macro battle_label_font_codes() {",
             '    """The copy list\'s label entries: the 8x8 font codes of the labels\' tiles."""',
             _db(entries), "}"]
    for name, row in rows.items():
        lines += ["", f".macro battle_label_{name}() {{", f'    """{texts[name][0]}: its row of battle tiles."""',
                  _db(row), "}"]
    return "\n".join(lines) + "\n"


def build(font_8x8: Path, menu_font: Path, glyphs: Glyphs, table: Path, include: Path, lang: str = "fr") -> None:
    """Bake `lang`'s labels into `font_8x8` in place and write `include`."""
    merged, text = bake(font_8x8.read_bytes(), VwfFont.decode(menu_font.read_bytes()), glyphs, Table(str(table)), lang)
    font_8x8.write_bytes(merged)
    include.write_text(text, encoding="utf-8")
