"""
The dialogue's 8x8 labels (the inn's Oui / Non window and the gils window's caption) pre-rendered in the small VWF
and baked into the 8x8 font at build time, in blank kana slots no table maps.

A dialogue copies the 8x8 font from $0A:F000 to BG3's tiles at $6000 (dialog/vwf.s `vwfinit`), so a baked tile
shows in those windows under its font code. The windows are fixed tilemaps in ROM: `dialog_labels.i` gives each
label its row of tilemap words (priority, palette 0, the code), a whole-tile layout like the 8x8 letters it replaces.
"""

from __future__ import annotations

from pathlib import Path

from katsuji import VwfFont
from katsuji.script import Table

from utils.bake_names import Glyphs, auto_kern, last_tile_columns, name_tiles
from utils.battle_labels import BLANK, BLANK_CODE, TILE_BYTES

SLOTS = range(0xB0, 0xC0)  # blank, unmapped kana slots of the 8x8 font
ATTR = 0x2000  # the windows' tilemap attribute: priority, palette 0
LABELS = {  # label: its text, the cells of its row, its alignment in them
    "yes": ("Oui", 3, "left"),  # the Yes / No window's inside after the cursor (dialog/patches.s)
    "no": ("Non", 3, "left"),
    "gils": ("Gils", 8, "right"),  # the gils window's inside (dialog/vwf.s _gils_window_size - 2)
}
TEXTS = {"en": {"yes": "Yes", "no": "No", "gils": "Gil"}}  # other languages' texts, LABELS' rows


def labels(lang: str = "fr") -> dict[str, tuple[str, int, str]]:
    """LABELS with `lang`'s texts."""
    texts = TEXTS.get(lang, {})
    return {name: (texts.get(name, text), cells, align) for name, (text, cells, align) in LABELS.items()}


def _lead(font: VwfFont, codes: bytes, cells: int, align: str) -> int:
    """The blank pixel columns before the text: none on the left, the row's slack on the right."""
    if align == "left":
        return 0
    width = (len(name_tiles(font, codes)) // TILE_BYTES - 1) * 8 + last_tile_columns(font, codes)
    return max(cells * 8 - width, 0)


def bake(font_8x8: bytes, font: VwfFont, glyphs: Glyphs, table: Table, lang: str = "fr") -> tuple[bytes, str]:
    """`font_8x8` with the labels' tiles in SLOTS, and the asm include giving their rows."""
    texts = labels(lang)
    codes = {name: table.to_bytes(text) for name, (text, _, _) in texts.items()}
    font = auto_kern(font, glyphs, list(codes.values()))
    merged = bytearray(font_8x8)
    slots = iter(SLOTS)
    rows: dict[str, list[int]] = {}
    for name, (text, cells, align) in texts.items():
        lead = _lead(font, codes[name], cells, align)
        tiles = name_tiles(font, codes[name], lead % 8)
        count = len(tiles) // TILE_BYTES
        if lead // 8 + count > cells:
            raise ValueError(f"{text!r} takes {count} tiles, its row has {cells} cells")
        row = [BLANK_CODE] * (lead // 8)
        for index in range(count):
            slot = next(slots, None)
            if slot is None:
                raise ValueError(f"the labels outgrow the font's {len(SLOTS)} free slots")
            cell = slice(slot * TILE_BYTES, (slot + 1) * TILE_BYTES)
            if merged[cell] != BLANK:
                raise ValueError(f"font tile {slot:#04x} is not blank: a label would overwrite a glyph")
            merged[cell] = tiles[index * TILE_BYTES:(index + 1) * TILE_BYTES]
            row.append(slot)
        rows[name] = row + [BLANK_CODE] * (cells - len(row))
    return bytes(merged), _include(rows, texts)


def _include(rows: dict[str, list[int]], texts: dict[str, tuple[str, int, str]]) -> str:
    lines = ['"""Generated by utils/dialog_labels.py: the dialogue labels\' baked tiles."""']
    for name, row in rows.items():
        words = ", ".join(f"0x{ATTR | code:04X}" for code in row)
        lines += ["", f".macro dialog_label_{name}() {{", f'    """{texts[name][0]}: its row of tilemap words."""',
                  f"    .dw {words}", "}"]
    return "\n".join(lines) + "\n"


def build(font_8x8: Path, menu_font: Path, glyphs: Glyphs, table: Path, include: Path, lang: str = "fr") -> None:
    """Bake `lang`'s labels into `font_8x8` in place and write `include`."""
    merged, text = bake(font_8x8.read_bytes(), VwfFont.decode(menu_font.read_bytes()), glyphs, Table(str(table)), lang)
    font_8x8.write_bytes(merged)
    include.write_text(text, encoding="utf-8")
